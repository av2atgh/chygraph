def _fit(k, y, kmax=1.0):
    """Power-law exponent of y ~ k^theta, fitted on k <= kmax."""
    k, y = np.asarray(k), np.asarray(y)
    m = (k <= kmax) & (y > 0)
    return float(np.polyfit(np.log(k[m]), np.log(y[m]), 1)[0])


