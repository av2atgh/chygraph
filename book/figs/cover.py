def _split(cards, kbar):
    """Layer chy-degrees splitting an induced mean degree ``kbar`` evenly.

    A layer-``l`` complex supplies ``c_l - 1`` neighbours per member, so the
    induced mean degree is ``sum_l kappa_l (c_l - 1)``.  Holding that fixed is
    what makes the six rows comparable: they are the same graph density
    arranged into different complexes.
    """
    return [kbar / len(cards) / (c - 1) for c in cards]


# ------------------------------------------- (6) the correlated-graph transition
VW_TAUS = (2.5, 3.0)
VW_DMAX = 800


def _vw_lambda(r, e, q, pi):
    """|leading eigenvalue| of the Jacobian, from the secular equation.

    ``J = -r diag(a) - (1-r) 1 (q a)^T`` with ``a_d = d (1-pi_d)^{d-1}`` is
    diagonal plus rank one, so with ``mu = -lambda`` its leading eigenvalue is
    the unique root of ``(1-r) sum_d q_d a_d / (mu - r a_d) = 1`` above
    ``r max(a)``.  No eigensolve, and ``vertexcover.is_unstable`` is the same
    statement evaluated at ``mu = 1``.
    """
    from scipy.optimize import brentq
    a = vc.jacobian_spectrum(r, e, q, pi)
    lo = r * a.max() + 1e-12
    g = lambda mu: (1 - r) * (q * a / (mu - r * a)).sum() - 1.0
    hi = max(lo * 2, 4.0)
    while g(hi) > 0:
        hi *= 2
    return brentq(g, lo, hi, xtol=1e-13) if g(lo) > 0 else lo


def _vw(tau, dmax=VW_DMAX, n=61):
    """x_c(r) and the leading |eigenvalue| along VW03 Eq. (18), at fixed p_d.

    The map is anti-monotone, so its fixed point is reached by bisection on the
    one scalar the correlation model closes on rather than by iteration, and
    stability is then asked of the Jacobian there.  That is what lets the curve
    be drawn past r_c at all: VW03's own instrument -- the iteration failing to
    converge -- cannot report a fixed point it never reaches.
    """
    p = vc.scale_free(tau, dmax)
    e, q, _ = vc.excess(p)
    r = np.linspace(0.0, 1.0, n)
    x = np.empty(n)
    lam = np.empty(n)
    for i, ri in enumerate(r):
        pi = vc.solve(ri, e, q)
        x[i] = vc.cover_size(p, pi)
        lam[i] = _vw_lambda(ri, e, q, pi)
    return r, x, lam, vc.rsb_point(tau, dmax)


def check_vw():
    """Sec. 11.8: the uncorrelated corner, and where replica symmetry breaks."""
    for k in (1.0, 2.0, 3.0, 5.0, 10.0):
        p = vc.poisson(k, 4000)
        e, q, _ = vc.excess(p)
        W = float(np.real(lambertw(k)))
        wh = 1 - (2 * W + W**2) / (2 * k)
        x = vc.cover_size(p, vc.solve(0.0, e, q))
        assert abs(x - wh) < 1e-12, (k, x, wh)
    print('  Eq. (11.12) at e_dd\' = q_d q_d\' returns Weigt-Hartmann to 1e-12')
    print('    at <k> = 1, 2, 3, 5, 10')

    def unstable(k):                       # the uncorrelated Poisson corner
        p = vc.poisson(k, 4000)
        e, q, _ = vc.excess(p)
        return vc.is_unstable(0.0, e, q, vc.solve(0.0, e, q))
    lo, hi = 1.0, 5.0
    for _ in range(60):
        m = 0.5 * (lo + hi)
        lo, hi = (lo, m) if unstable(m) else (m, hi)
    kc = 0.5 * (lo + hi)
    assert abs(kc - np.e) < 1e-12, kc
    print(f'  its instability there   <k> = {kc:.12f}')
    print(f'  e                       <k> = {np.e:.12f}')
    print('    a third route to Sec. 11.4\'s number, on a different code path')

    p = vc.scale_free(2.5, 200)                 # secular root vs dense eigensolve
    e, q, _ = vc.excess(p)
    d = max(abs(_vw_lambda(ri, e, q, vc.solve(ri, e, q))
                - abs(vc.leading_eigenvalue(ri, e, q, vc.solve(ri, e, q))))
            for ri in (0.2, 0.5, 0.8))
    assert d < 1e-9, d
    print(f'  secular root agrees with a dense eigensolve to {d:.1e}')

    for tau in VW_TAUS:
        r, x, lam, rc = _vw(tau, n=11)
        i = int(np.argmin(np.abs(r - 0.7)))
        print(f'  tau = {tau}: r_c = {rc:.4f}, '
              f'x_c from {x[0]:.4f} at r = 0 to {x[i]:.4f} at r = {r[i]:.1f} '
              f'({100*(x[i]/x[0]-1):.0f} per cent)')
    print('  the heavier tail breaks first, and p_d has not moved')


