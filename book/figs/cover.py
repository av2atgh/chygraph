    ax.set_xlabel('transitivity $T$', fontsize=8.5)
    ax.set_ylabel(r'core $P_{C}(\mathrm{VC},\mathrm{G})$', fontsize=8.5)
    ax.set_xlim(-0.004, max(z['trans'] for z in rows) * 1.04)
