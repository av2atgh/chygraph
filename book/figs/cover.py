    for tau in VW_TAUS:
        col, mk = styles[tau]
        d = sorted((z for z in rows if abs(z['tau'] - tau) < 1e-9),
                   key=lambda z: z['r'])
        rm = np.array([z['r'] for z in d])
        tm = np.array([z['trans'] for z in d])
        tc[tau] = float(np.interp(vc.rsb_point(tau, VW_DMAX), rm, tm))
        ax.errorbar(tm, [z['core'] for z in d], [z['core_sd'] for z in d],
                    [z['trans_sd'] for z in d], fmt=mk, ms=3.6, lw=0,
                    elinewidth=0.7, capsize=1.4, mfc='white', mew=0.9,
                    color=col, label=rf'$\tau={tau}$')
